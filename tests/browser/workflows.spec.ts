import { expect, test } from '@playwright/test';

test('investigation, linked actions, closure checks and persistence', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Log observation', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Title', { exact: true }).fill('Damaged mooring line');
  await dialog.getByLabel('Location').fill('Aft deck');
  await dialog.getByLabel('Description', { exact: true }).fill('Outer braid found damaged before mooring.');
  await dialog.getByRole('button', { name: 'Save observation' }).click();
  await page.getByRole('button', { name: /Damaged mooring line/ }).click();
  await page.getByRole('button', { name: 'Add linked action' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Action title').fill('Replace mooring line');
  await dialog.getByRole('button', { name: 'Save action' }).click();
  await page.getByRole('button', { name: /Damaged mooring line/ }).click();
  await page.getByRole('button', { name: 'Edit / investigate' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Closed');
  await dialog.getByLabel('Investigation / closure findings').fill('Line quarantined and replaced.');
  await dialog.getByRole('button', { name: 'Save observation' }).click();
  await expect(page.getByText(/Complete the linked corrective actions/)).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Actions', exact: true }).click();
  await page.getByRole('row').filter({ hasText: 'Replace mooring line' }).getByRole('button', { name: 'Edit' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Complete');
  await dialog.getByLabel('Completion evidence / notes').fill('New line installed and inspected by bosun.');
  await dialog.getByRole('button', { name: 'Save action' }).click();
  await page.getByRole('button', { name: 'Incidents', exact: false }).first().click();
  await page.getByRole('row').filter({ hasText: 'Damaged mooring line' }).getByRole('button', { name: 'Open' }).click();
  await page.getByRole('button', { name: 'Edit / investigate' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Closed');
  await dialog.getByLabel('Investigation / closure findings').fill('Replacement verified and crew briefed.');
  await dialog.getByRole('button', { name: 'Save observation' }).click();
  await page.reload();
  await page.getByRole('button', { name: /^Incidents/ }).click();
  await expect(page.getByRole('row').filter({ hasText: 'Damaged mooring line' })).toContainText('Closed');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export report' }).click();
  expect((await download).suggestedFilename()).toBe('safewatch-incidents.csv');
  expect(errors).toEqual([]);
});

test('risk scoring and drill records survive navigation and reload', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Risk register', exact: true }).click();
  await page.getByRole('button', { name: 'New assessment' }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Hazard', { exact: true }).fill('Test lifting hazard');
  await dialog.getByLabel('Activity', { exact: true }).fill('Crane lift');
  await dialog.getByLabel('Residual likelihood (1–5)').selectOption('4');
  await dialog.getByLabel('Residual consequence (1–5)').selectOption('5');
  await dialog.getByLabel('Controls in place').fill('Certified gear, exclusion zone, banksman.');
  await expect(dialog.getByText('Residual score: 20 · High')).toBeVisible();
  await dialog.getByRole('button', { name: 'Save assessment' }).click();
  await page.getByRole('button', { name: 'Drills', exact: true }).click();
  await page.locator('.drill-card').filter({ hasText: 'Abandon ship drill' }).getByRole('button', { name: 'Record completion' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Findings / lessons learned').fill('Muster completed in 6 minutes; radios checked.');
  await dialog.getByRole('button', { name: 'Save drill record' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Drills', exact: true }).click();
  await expect(page.getByText('Muster completed in 6 minutes; radios checked.')).toBeVisible();
  await expect(page.locator('.drill-card').filter({ hasText: 'Abandon ship drill' })).toContainText('Ready');
  await page.getByRole('button', { name: 'Risk register', exact: true }).click();
  await expect(page.getByText('Test lifting hazard', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('safewatch-desktop.png'), fullPage: true, animations: 'disabled' });
});

